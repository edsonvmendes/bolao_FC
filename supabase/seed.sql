insert into public.scoring_rules (pool_id)
select id from public.pools
where name = 'Bolao da Resenha - Copa 2026'
on conflict (pool_id) do nothing;

do $$
declare
  v_pool_id uuid;
  codes text[] := array[
    'br','jp','mx','ma','ar','de','kr','sn','fr','us','gh','uy',
    'pt','ca','eg','nl','es','gb-eng','co','au','ba','ch','ec','qa',
    'hr','be','py','sa','no','tr','za','nz','se','at','tn','ir',
    'gb-sct','cz','dz','uz','pa','ci','jo','cv','ht','cd','iq','cw'
  ];
  pairings int[][] := array[
    array[1,2], array[3,4], array[1,3], array[4,2], array[4,1], array[2,3]
  ];
  group_index int;
  pairing_index int;
  group_codes text[];
  home_id uuid;
  away_id uuid;
  match_time timestamptz;
begin
  select id into v_pool_id
  from public.pools
  where name = 'Bolao da Resenha - Copa 2026'
  limit 1;

  for group_index in 0..11 loop
    group_codes := codes[(group_index * 4 + 1):(group_index * 4 + 4)];

    for pairing_index in 1..6 loop
      select id into home_id from public.teams where country_code = group_codes[pairings[pairing_index][1]];
      select id into away_id from public.teams where country_code = group_codes[pairings[pairing_index][2]];
      match_time := timestamptz '2026-06-11 16:00:00-03'
        + make_interval(days => group_index + pairing_index - 1)
        + make_interval(hours => case when pairing_index in (2, 4) then 3 else 0 end);

      insert into public.matches (
        pool_id,
        phase,
        group_name,
        round_number,
        home_team_id,
        away_team_id,
        match_datetime,
        prediction_deadline
      )
      select
        v_pool_id,
        'group_stage',
        'Grupo ' || chr(65 + group_index),
        case when pairing_index <= 2 then 1 when pairing_index <= 4 then 2 else 3 end,
        home_id,
        away_id,
        match_time,
        match_time - interval '30 minutes'
      where not exists (
        select 1 from public.matches
        where matches.pool_id = v_pool_id
          and home_team_id = home_id
          and away_team_id = away_id
          and match_datetime = match_time
      );
    end loop;
  end loop;
end;
$$;
